## 道具2: 無差別曲線

**無差別曲線**は、消費者にとって「満足度が同じになる2財の組み合わせ」を結んだ曲線です。

- 右下がりの曲線になる（片方を減らしたら、もう片方を増やさないと同じ満足を保てない）
- 原点から遠い曲線ほど満足度が高い
- 互いに交わらない
- 原点に向かって凸の形になる

