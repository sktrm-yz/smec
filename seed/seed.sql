## 需要曲線 — 安いほどたくさん買いたい

**需要曲線**は、価格と「消費者が買いたい量」の関係を表します。

- 価格が下がる → 買いたい人が増える → 需要量は増える
- 価格が上がる → 買いたい人が減る → 需要量は減る

グラフにすると**右下がり**の曲線になります。

価格以外の要因（所得が増えた、流行した など）で買いたい量が変わるときは、曲線そのものが左右に**シフト**します。ここは試験でよく問われる区別です。

- 価格の変化 → 曲線**上**の移動
- 価格以外の変化 → 曲線**自体**のシフト

## 供給曲線 — 高いほどたくさん売りたい

**供給曲線**は、価格と「企業が売りたい量」の関係を表します。価格が高いほど利益が出るので、企業はたくさん作ろうとします。グラフは**右上がり**です。

原材料費の低下や技術進歩が起きると、同じ価格でもより多く供給できるため、供給曲線は右にシフトします。

## 市場均衡 — 2つの曲線が交わる点

需要曲線と供給曲線の交点を**均衡点**と呼び、そこでの価格を**均衡価格**、取引量を**均衡取引量**といいます。

- 価格が均衡より高い → 売りたい量 > 買いたい量 → **超過供給**（売れ残り）→ 価格は下がる
- 価格が均衡より低い → 買いたい量 > 売りたい量 → **超過需要**（品不足）→ 価格は上がる

つまり市場には、価格が自動的に均衡へ向かう調整メカニズムが備わっています。これを**価格の自動調節機能**と呼びます。

